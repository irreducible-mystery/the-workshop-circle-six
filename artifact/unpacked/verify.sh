#!/bin/sh
# verify.sh — one command. Exit 0 iff every claim in this artifact checks.
#
# Checks, in order:
#   1. a Lean kernel is present and is HONEST (accepts a truth, REJECTS a falsehood)
#   2. both Lean files compile
#   3. every declaration in them depends on NO axiom
#   4. 01-BUILD-STACK.md still matches the source it was generated from
#   5. the compute/ scripts run
#   6. MANIFEST.sha256 matches
#
# Read the exit code, not the text.
set -u
FAIL=0
say() { printf '%s\n' "$*"; }
bad() { printf '  FAIL  %s\n' "$*"; FAIL=1; }
ok()  { printf '  ok    %s\n' "$*"; }

say "=============================================================="
say " circle-six-gap-proof — verification"
say "=============================================================="

# ---------------------------------------------------------------- 1. kernel
say ""
say "[1] kernel present and honest"
if ! command -v lean >/dev/null 2>&1; then
    say "  no 'lean' on PATH."
    say ""
    say "  Install Lean 4.22.0 (no Mathlib needed — these files import nothing):"
    say "    curl -sSL -o lean.tar.zst \\"
    say "      https://github.com/leanprover/lean4/releases/download/v4.22.0/lean-4.22.0-linux.tar.zst"
    say "    zstd -d lean.tar.zst -o lean.tar && tar -xf lean.tar"
    say "    export PATH=\$PWD/lean-4.22.0-linux/bin:\$PATH"
    exit 1
fi
VER=$(lean --version 2>&1)
say "  $VER"
case "$VER" in
    *4.22.0*) ok "version matches the one this was built with" ;;
    *) say "  NOTE: built with 4.22.0; you have something else. Proceeding." ;;
esac
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
printf 'theorem t : 2 + 2 = 4 := by decide\n' > "$T/ok.lean"
printf 'theorem f : 2 + 2 = 5 := by decide\n' > "$T/no.lean"
lean "$T/ok.lean" >/dev/null 2>&1 && ok "kernel accepts 2+2=4" || bad "kernel REJECTS a truth"
lean "$T/no.lean" >/dev/null 2>&1 && bad "kernel ACCEPTS 2+2=5 — not usable" || ok "kernel rejects 2+2=5"

# ---------------------------------------------------------------- 2. compile
say ""
say "[2] the proofs compile"
for f in lean/C6_Twist.lean lean/C6_Gap.lean; do
    S=$(date +%s)
    if lean "$f" >"$T/out" 2>&1; then ok "$f  EXIT=0  ($(( $(date +%s) - S ))s)"
    else bad "$f did not compile"; head -20 "$T/out"; fi
done

# ---------------------------------------------------------------- 3. axioms
say ""
say "[3] axiom audit — every declaration, not a sample"
mkdir -p audit
rm -f audit/AUDIT.txt.new
TOTAL=0; CLEAN=0
for f in lean/C6_Twist.lean lean/C6_Gap.lean; do
    python3 - "$f" "$T" <<'PY'
import re,sys,os
f,T=sys.argv[1],sys.argv[2]
s=open(f).read()
top=re.findall(r'^(?:theorem|def|abbrev|instance|structure)\s+([A-Za-z_][A-Za-z_0-9\'.]*)',s,re.M)
ns=[];cur=None
for line in s.splitlines():
    m=re.match(r'^namespace\s+(\S+)',line)
    if m: cur=m.group(1); continue
    if re.match(r'^end\s',line): cur=None; continue
    m=re.match(r'^(?:theorem|def|abbrev|instance)\s+([A-Za-z_][A-Za-z_0-9\'.]*)',line)
    if m and cur: ns.append(f"{cur}.{m.group(1)}")
seen=set();names=[]
for n in top+ns:
    b=n.split('.')[-1]
    if any(x.endswith('.'+b) for x in ns) and '.' not in n: continue
    if n not in seen: seen.add(n); names.append(n)
open(os.path.join(T,"aud_"+os.path.basename(f)),"w").write(
    s+"\n\n"+"\n".join(f"#print axioms {n}" for n in names)+"\n")
PY
    lean "$T/aud_$(basename $f)" > "$T/res_$(basename $f)" 2>&1
    n=$(grep -c '^' "$T/res_$(basename $f)")
    c=$(grep -c 'does not depend on any axioms' "$T/res_$(basename $f)")
    TOTAL=$((TOTAL+n)); CLEAN=$((CLEAN+c))
    cat "$T/res_$(basename $f)" >> audit/AUDIT.txt.new
    if [ "$n" -eq "$c" ]; then ok "$f — $n declarations, all axiom-free"
    else bad "$f — $n declarations, only $c axiom-free"; grep 'depends on' "$T/res_$(basename $f)"; fi
done
for a in propext Classical.choice Quot.sound sorryAx ofReduceBool ofReduceNat; do
    # NB: grep -c prints 0 and EXITS 1 when there are no matches. Piping that
    # through "|| echo 0" appends a SECOND zero and the test then dies on
    # "Illegal number". Use || true, which adds nothing.
    k=$(grep -c "$a" audit/AUDIT.txt.new 2>/dev/null || true)
    k=${k:-0}
    if [ "$k" -eq 0 ]; then ok "no $a"; else bad "$a appears $k times"; fi
done
{ printf 'Axiom audit — regenerated by verify.sh\n\n'
  printf 'declarations audited : %s\n' "$TOTAL"
  printf 'depend on NO axiom   : %s\n\n' "$CLEAN"
  cat audit/AUDIT.txt.new; } > audit/AUDIT.txt
rm -f audit/AUDIT.txt.new

# ---------------------------------------------------------------- 4. doc drift
say ""
say "[4] 01-BUILD-STACK.md still matches the source"
if [ -x ./regen-build-stack.py ] || [ -f ./regen-build-stack.py ]; then
    python3 ./regen-build-stack.py > "$T/bs.md" 2>/dev/null
    if diff -q "$T/bs.md" 01-BUILD-STACK.md >/dev/null 2>&1; then
        ok "no drift between doc and source"
    else
        bad "01-BUILD-STACK.md has DRIFTED from lean/*.lean"
        diff "$T/bs.md" 01-BUILD-STACK.md | head -20
    fi
else
    bad "regen-build-stack.py missing — cannot check drift"
fi

# ---------------------------------------------------------------- 5. compute
say ""
say "[5] the computed (NOT kernel-decided) scripts run"
for p in compute/*.py; do
    if python3 "$p" >/dev/null 2>&1; then ok "$p"
    else bad "$p exited non-zero"; fi
done

# ---------------------------------------------------------------- 6. manifest
say ""
say "[6] file checksums"
if [ -f MANIFEST.sha256 ]; then
    if sha256sum -c MANIFEST.sha256 >"$T/sums" 2>&1; then ok "all files match MANIFEST.sha256"
    else bad "checksum mismatch"; grep -v ': OK$' "$T/sums" | head -20; fi
else
    bad "MANIFEST.sha256 missing"
fi

say ""
say "=============================================================="
if [ $FAIL -eq 0 ]; then
    say " ALL CHECKS PASSED"
    say ""
    say " What this does NOT establish is in NOT-PROVED.md. Read it."
else
    say " SOMETHING FAILED — see the FAIL lines above"
fi
say "=============================================================="
exit $FAIL
